void test_draw_string(void) {
    char buff[2] = {0, 0}; // 单字符缓冲区
    uint8_t x = 0, y = 0; // 起始坐标

    // 循环绘制所有字符 (0x20 到 0x7F + degrees, tick)
    for (uint8_t charIndex = 0x20; charIndex <= 0x7F; charIndex++) {
        buff[0] = charIndex; // 当前字符
        // 计算绘制位置（每行 18 个字符，7 像素宽，7 像素高）
        const uint8_t xx = (charIndex - 0x20) % 18 * 7; // 每行 18 字符 (128 / 7 ≈ 18)
        const uint8_t yy = ((charIndex - 0x20) / 18) * 8; // 每 8 像素一行，共 6 行
        draw_string(buff, false, xx, yy);
    }

}

